            'en' => '/contact',
            'pl' => '/pl/contact',
        ],
        name: 'contact',
        methods: ['GET'],
    )]
    public function index(): Response
    {
        return $this->render('contact/index.html.twig', [
            'controller_name' => 'ContactController',
        ]);
    }
}
